"""Regenerate portable Lambda dependency inputs from pyproject.toml."""
from pathlib import Path
import tomllib
root = Path(__file__).resolve().parents[1]
project = tomllib.loads((root / "pyproject.toml").read_text())["project"]
for extra, filename in (("web", "lambda_web_requirements.txt"), ("worker", "lambda_requirements.txt")):
    requirements = list(dict.fromkeys(project["dependencies"] + project["optional-dependencies"][extra]))
    (root / "terraform" / filename).write_text("# Generated by scripts/export_requirements.py; edit pyproject.toml.\n" + "\n".join(requirements) + "\n")
